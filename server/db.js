"use strict";
// PostgreSQL access. Production uses Supabase (any PostgreSQL) through the `pg` driver.
// Local development and automated tests can use PGlite (PostgreSQL running inside Node, no install needed).
//
// Every method is async. SQL is written with "?" placeholders and converted to $1, $2, ... here.
//   db.get(sql, ...params)     -> first row or undefined
//   db.all(sql, ...params)     -> array of rows
//   db.run(sql, ...params)     -> { changes }
//   db.insert(sql, ...params)  -> new row id (adds RETURNING id)
//   db.tx(async (t) => {...})  -> runs the callback in one transaction; `t` has get/all/run/insert
const fs = require("fs");
const path = require("path");

const SCHEMA = `
CREATE TABLE IF NOT EXISTS departments (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL UNIQUE
);
CREATE TABLE IF NOT EXISTS users (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  role TEXT NOT NULL CHECK (role IN ('student','staff','provider','admin')),
  login TEXT NOT NULL UNIQUE,
  first_name TEXT NOT NULL,
  last_name TEXT NOT NULL,
  password_hash TEXT NOT NULL,
  active INTEGER NOT NULL DEFAULT 1,
  department_id INTEGER REFERENCES departments(id),
  created_at TEXT NOT NULL DEFAULT to_char(timezone('utc', now()), 'YYYY-MM-DD HH24:MI:SS')
);
CREATE TABLE IF NOT EXISTS availability (
  provider_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  weekday INTEGER NOT NULL CHECK (weekday BETWEEN 0 AND 6),
  working INTEGER NOT NULL DEFAULT 0,
  start_time TEXT NOT NULL DEFAULT '09:00',
  end_time TEXT NOT NULL DEFAULT '12:00',
  PRIMARY KEY (provider_id, weekday)
);
CREATE TABLE IF NOT EXISTS blocked_dates (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  provider_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  date TEXT NOT NULL,
  reason TEXT NOT NULL,
  UNIQUE (provider_id, date)
);
CREATE TABLE IF NOT EXISTS appointments (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  student_id INTEGER NOT NULL REFERENCES users(id),
  provider_id INTEGER NOT NULL REFERENCES users(id),
  date TEXT NOT NULL,
  time TEXT NOT NULL,
  status TEXT NOT NULL DEFAULT 'Booked' CHECK (status IN ('Booked','Checked in','Completed','No-show','Cancelled')),
  cancel_reason TEXT,
  cancelled_by INTEGER REFERENCES users(id),
  created_by INTEGER NOT NULL REFERENCES users(id),
  created_at TEXT NOT NULL DEFAULT to_char(timezone('utc', now()), 'YYYY-MM-DD HH24:MI:SS')
);
-- Conflict prevention enforced by the database itself: one active booking per provider slot,
-- and one active booking per student at the same time.
CREATE UNIQUE INDEX IF NOT EXISTS ux_provider_slot ON appointments (provider_id, date, time) WHERE status <> 'Cancelled';
CREATE UNIQUE INDEX IF NOT EXISTS ux_student_slot ON appointments (student_id, date, time) WHERE status <> 'Cancelled';
CREATE INDEX IF NOT EXISTS ix_appt_date ON appointments (date);
CREATE INDEX IF NOT EXISTS ix_appt_student ON appointments (student_id);
CREATE TABLE IF NOT EXISTS notifications (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  appointment_id INTEGER REFERENCES appointments(id),
  type TEXT NOT NULL,
  title TEXT NOT NULL,
  body TEXT NOT NULL,
  is_read INTEGER NOT NULL DEFAULT 0,
  created_at TEXT NOT NULL DEFAULT to_char(timezone('utc', now()), 'YYYY-MM-DD HH24:MI:SS')
);
CREATE INDEX IF NOT EXISTS ix_notif_user ON notifications (user_id);
CREATE TABLE IF NOT EXISTS audit_log (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  at TEXT NOT NULL DEFAULT to_char(timezone('utc', now()), 'YYYY-MM-DD HH24:MI:SS'),
  user_id INTEGER,
  user_name TEXT NOT NULL,
  action TEXT NOT NULL,
  target TEXT NOT NULL DEFAULT ''
);
-- Supabase publishes every table in the "public" schema through its own web API unless Row Level Security is on.
-- Turning it on with no policies blocks that API completely. This server connects as the database owner,
-- which is not affected, so the app keeps working and nobody can read these tables with the public API key.
ALTER TABLE departments ENABLE ROW LEVEL SECURITY;
ALTER TABLE users ENABLE ROW LEVEL SECURITY;
ALTER TABLE availability ENABLE ROW LEVEL SECURITY;
ALTER TABLE blocked_dates ENABLE ROW LEVEL SECURITY;
ALTER TABLE appointments ENABLE ROW LEVEL SECURITY;
ALTER TABLE notifications ENABLE ROW LEVEL SECURITY;
ALTER TABLE audit_log ENABLE ROW LEVEL SECURITY;
`;

const toPg = (sql) => { let i = 0; return sql.replace(/\?/g, () => "$" + (++i)); };

/* q(sql, params) -> { rows, count }. Both drivers are adapted to this one shape. */
function wrap(q, exec, tx) {
  const api = {
    exec,
    all: async (sql, ...p) => (await q(toPg(sql), p)).rows,
    get: async (sql, ...p) => (await q(toPg(sql), p)).rows[0],
    run: async (sql, ...p) => ({ changes: (await q(toPg(sql), p)).count }),
    insert: async (sql, ...p) => (await q(toPg(sql) + " RETURNING id", p)).rows[0].id,
    tx
  };
  return api;
}

async function openPg(url) {
  const { Pool, types } = require("pg");
  types.setTypeParser(20, (v) => parseInt(v, 10)); // COUNT(*) and other bigint values come back as numbers
  const u = new URL(url);
  const local = ["localhost", "127.0.0.1", "::1", "[::1]"].includes(u.hostname);
  u.searchParams.delete("sslmode"); // we set SSL explicitly below
  const pool = new Pool({ connectionString: u.toString(), max: 5, connectionTimeoutMillis: 15000, idleTimeoutMillis: 30000, ssl: local ? false : { rejectUnauthorized: false } });
  pool.on("error", (e) => console.error("[db] idle connection error:", e.message));
  const norm = (r) => ({ rows: r.rows || [], count: r.rowCount });
  const db = wrap(
    async (sql, p) => norm(await pool.query(sql, p)),
    async (sql) => { await pool.query(sql); },
    async (fn) => {
      const c = await pool.connect();
      try {
        await c.query("BEGIN");
        const out = await fn(wrap(async (sql, p) => norm(await c.query(sql, p)), async (sql) => { await c.query(sql); }, null));
        await c.query("COMMIT");
        return out;
      } catch (e) {
        await c.query("ROLLBACK").catch(() => {});
        throw e;
      } finally { c.release(); }
    }
  );
  db.close = () => pool.end();
  return db;
}

async function openPglite(dir) {
  const { PGlite } = require("@electric-sql/pglite");
  if (dir) fs.mkdirSync(path.dirname(dir), { recursive: true });
  const pg = dir ? await PGlite.create(dir) : await PGlite.create();
  const norm = (r) => ({ rows: r.rows || [], count: r.affectedRows });
  const db = wrap(
    async (sql, p) => norm(await pg.query(sql, p)),
    async (sql) => { await pg.exec(sql); },
    (fn) => pg.transaction((t) => fn(wrap(async (sql, p) => norm(await t.query(sql, p)), async (sql) => { await t.exec(sql); }, null)))
  );
  db.close = () => pg.close();
  return db;
}

/* target: a postgres:// connection string (Supabase), "pglite:<folder>" (local files), or ":memory:" (tests). */
async function openDb(target) {
  let db;
  if (!target || target === ":memory:") db = await openPglite(null);
  else if (target.startsWith("pglite:")) db = await openPglite(target.slice(7));
  else db = await openPg(target);
  await db.exec(SCHEMA);
  return db;
}

/* Unique-constraint violation (PostgreSQL error code 23505): two people took the same slot at once. */
const isConflict = (e) => !!e && e.code === "23505";

module.exports = { openDb, isConflict, SCHEMA };
